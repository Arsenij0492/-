# ========== ФУНКЦИИ ДЛЯ РАБОТЫ С БАЗОЙ ==========

def _is_real_term(item):
    """Проверяет, является ли элемент настоящим термином"""
    return isinstance(item, dict) and 'translation' in item

def find_term(query: str):
    """Строгий поиск термина - ТОЛЬКО полное совпадение с ключом словаря"""
    query_lower = query.lower().strip()
    
    # Только прямое совпадение с ключом словаря
    if query_lower in TERMS_DATABASE and _is_real_term(TERMS_DATABASE[query_lower]):
        return TERMS_DATABASE[query_lower]
    
    return None

def get_all_terms():
    """Получить список всех настоящих терминов"""
    return [term for term, data in TERMS_DATABASE.items() if _is_real_term(data)]

def get_all_fields():
    """Получить список всех уникальных отраслей права"""
    fields = set()
    for term, data in TERMS_DATABASE.items():
        if _is_real_term(data) and 'field' in data:
            field_value = data['field']
            if ' / ' in field_value:
                for f in field_value.split(' / '):
                    fields.add(f.strip())
            else:
                fields.add(field_value)
    return sorted(list(fields))

def get_terms_by_field(field_name: str):
    """Получить список терминов по отрасли права"""
    terms = []
    for term, data in TERMS_DATABASE.items():
        if _is_real_term(data) and 'field' in data:
            field_value = data['field']
            if field_name in field_value or field_value == field_name:
                terms.append(term)
    return sorted(terms)